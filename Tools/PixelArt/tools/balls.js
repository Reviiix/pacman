#!/usr/bin/env node
// Generates the rolling-ball sprites in art.txt: a 14 px ball in a body colour with a shaded crescent along its bottom, a
// pair of bands half a ball apart that travel across it 2 px a frame (so it always shows rolling), and a white shine at
// the top centre. The shine and crescent are left-right symmetric, so mirroring a side strip for leftward travel never
// moves the light. Each ball gets three 4-frame strips: <name> (rolling right; mirrored in Unity for left), <up> and <down>.
// Usage: node tools/balls.js art.txt     rewrites the section between the BEGIN and END marker lines in art.txt
//        node tools/balls.js             prints the section instead
const fs = require('fs');
const BEGIN = '// ---------------------------------------------------------------- balls: generated by node tools/balls.js art.txt (edit its BALLS list and re-run, never hand-edit); 4-frame rolling strips for the player and each enemy';
const END = '// ---------------------------------------------------------------- end of generated balls';
const BALLS = [
  { name: 'hero_side', up: 'hero_up', down: 'hero_down', body: 'H', band: 'W', shade: 'F', note: 'player: bright green ball, white bands (a pattern no enemy shares, so red-green colour-blind players can still pick it out)' },
  { name: 'enemy_chase', up: 'enemy_chase_up', down: 'enemy_chase_down', body: 'R', band: 'C', note: 'Chase: scarlet ball, crimson band' },
  { name: 'enemy_cutoff', up: 'enemy_cutoff_up', down: 'enemy_cutoff_down', body: 'C', band: 'Q', note: 'CutOff: deep crimson ball, maroon band' },
  { name: 'enemy_scared', up: 'enemy_scared_up', down: 'enemy_scared_down', body: 'U', band: 'R', note: 'Scared: coral red ball, scarlet band' },
  { name: 'enemy_random', up: 'enemy_random_up', down: 'enemy_random_down', body: 'P', band: 'U', note: 'Random: light red ball, coral band' },
];
const SIZE = 16, CENTRE = 7.5, RADIUS = 7;
const BAND_STEPS = [0, 2, 4, 6];
const BAND_SPACING = 8;

/** Whether a pixel lies inside the ball. */
const inBall = (x, y) => (x - CENTRE) ** 2 + (y - CENTRE) ** 2 <= RADIUS ** 2;
/** Whether a pixel lies in the shaded crescent along the ball's bottom edge. */
const inCrescent = (x, y) => inBall(x, y) && (x - CENTRE) ** 2 + (y - CENTRE + 1.5) ** 2 > RADIUS ** 2;
/** Whether a pixel is part of the top-centre shine. */
const inShine = (x, y) => (y === 3 && x >= 6 && x <= 9) || (y === 4 && x >= 7 && x <= 8);

/** Draws one frame with two bands, half a ball apart, centred on the given column and the one 8 px on (vertical bands) or rows (horizontal bands), narrower near the rim. */
function frame(ball, along, at) {
  const rows = [];
  for (let y = 0; y < SIZE; y++) {
    let row = '';
    for (let x = 0; x < SIZE; x++) {
      if (!inBall(x, y)) { row += '.'; continue; }
      const position = along === 'x' ? x : y;
      let key = inCrescent(x, y) ? ball.shade || ball.band : ball.body;
      for (const centre of [at, at + BAND_SPACING]) {
        const halfWidth = centre >= 4 && centre <= 11 ? 1 : 0.5;
        if (Math.abs(position - centre) <= halfWidth) key = ball.band;
      }
      if (inShine(x, y)) key = 'W';
      row += key;
    }
    rows.push(row);
  }
  return rows;
}

/** Returns one 4-frame strip as art.txt lines. */
function strip(name, ball, along, steps, note) {
  const lines = [`// ---------------------------------------------------------------- ${note}`, `@sprite ${name}`];
  for (const at of steps) lines.push('@frame', ...frame(ball, along, at));
  return [...lines, ''];
}

const section = [BEGIN, ''];
for (const ball of BALLS) {
  section.push(...strip(ball.name, ball, 'x', BAND_STEPS, `${ball.note}; rolling right, bands moving right (mirrored in code for left)`));
  section.push(...strip(ball.up, ball, 'y', [...BAND_STEPS].reverse(), `${ball.note}; rolling up, bands moving up`));
  section.push(...strip(ball.down, ball, 'y', BAND_STEPS, `${ball.note}; rolling down, bands moving down`));
}
section.push(END);
const artFile = process.argv[2];
if (!artFile) {
  console.log(section.join('\n'));
} else {
  const art = fs.readFileSync(artFile, 'utf8');
  const start = art.indexOf(BEGIN), end = art.indexOf(END);
  if (start < 0 || end < start) throw new Error(`${artFile} has no balls section between the marker lines`);
  fs.writeFileSync(artFile, art.slice(0, start) + section.join('\n') + art.slice(end + END.length));
  console.log(`balls: rewrote ${BALLS.length * 3} strips in ${artFile}`);
}
