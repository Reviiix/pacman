#!/usr/bin/env node
// Generates the wall quadrant patterns (8x8, authored as the north-east quadrant) from a distance field, one set per tile corner,
// so every band follows the same rounded contour and the top/left edges can be lit while the bottom/right edges sit in shade.
// Each corner set names the bands for its authored top edge and right edge; render.js flips the sets into place:
//   ne: top = north (lit),  right = east (shade)      nw: top = north (lit),  right = west (lit)
//   se: top = south (shade), right = east (shade)     sw: top = south (shade), right = west (lit)
// Run directly to print an "@walls corners" block for art.txt (optional glints are corner:pattern:x:y:key, x/y in the authored 8x8):
//   node walls.js <litBands> <shadeBands> <core> [radius=4] [inset=1] [glint...]
//   Candy Haunt walls: node walls.js LPD D J 4 2 nw:outer:4:3:W
function cornerSet({ top, right, core, R = 4, inset = 1, preferTopOnTie = true }) {
  const edge = 8 - inset;          // wall body spans x < edge (authored east side exposed)
  const topLine = inset;           // wall body spans y > topLine (authored north side exposed)
  const pick = (d, side) => {
    if (d <= 0) return '.';
    const bands = side === 'top' ? top : right;
    const b = Math.floor(d);
    return b < bands.length ? bands[b] : core;
  };
  const sideFromAngle = deg => (Math.abs(deg - 45) < 1e-6 ? (preferTopOnTie ? 'top' : 'right') : deg > 45 ? 'top' : 'right');
  const field = {
    horizontal: (px, py) => pick(py - topLine, 'top'),
    vertical: (px, py) => pick(edge - px, 'right'),
    outer: (px, py) => {
      const cx = edge - R, cy = topLine + R;
      if (px <= cx || py >= cy) {
        const dTop = py - topLine, dRight = edge - px;
        return dTop === dRight ? pick(dTop, preferTopOnTie ? 'top' : 'right') : dTop < dRight ? pick(dTop, 'top') : pick(dRight, 'right');
      }
      const deg = Math.atan2(cy - py, px - cx) * 180 / Math.PI;
      return pick(R - Math.hypot(px - cx, py - cy), sideFromAngle(deg));
    },
    inner: (px, py) => {
      if (px >= edge) return pick(py - topLine, 'top');
      if (py <= topLine) return pick(edge - px, 'right');
      const deg = Math.atan2(py - topLine, edge - px) * 180 / Math.PI;
      return pick(Math.hypot(edge - px, py - topLine), sideFromAngle(deg));
    },
    fill: () => core,
  };
  const out = {};
  for (const [name, f] of Object.entries(field)) {
    out[name] = [...Array(8).keys()].map(y => [...Array(8).keys()].map(x => f(x + 0.5, y + 0.5)).join(''));
  }
  return out;
}
// Top-left light: lit bands on north and west edges, shade bands on south and east edges.
function corners({ lit, shade, core, R = 4, inset = 1, glints = [] }) {
  const sets = {
    ne: cornerSet({ top: lit, right: shade, core, R, inset, preferTopOnTie: true }),
    nw: cornerSet({ top: lit, right: lit, core, R, inset }),
    se: cornerSet({ top: shade, right: shade, core, R, inset }),
    sw: cornerSet({ top: shade, right: lit, core, R, inset, preferTopOnTie: false }),
  };
  for (const [corner, pattern, x, y, key] of glints) {
    const rows = sets[corner][pattern];
    rows[y] = rows[y].slice(0, x) + key + rows[y].slice(x + 1);
  }
  return sets;
}
module.exports = { cornerSet, corners };
if (require.main === module) {
  const [lit = 'LPD', shade = 'D', core = 'J', R = '4', inset = '2', ...glintArgs] = process.argv.slice(2);
  const glints = glintArgs.map(g => { const [c, p, x, y, k] = g.split(':'); return [c, p, +x, +y, k]; });
  const sets = corners({ lit: [...lit], shade: [...shade], core, R: parseFloat(R), inset: parseInt(inset, 10), glints });
  console.log(`// generated by: node tools/walls.js ${lit} ${shade} ${core} ${R} ${inset}${glintArgs.length ? ' ' + glintArgs.join(' ') : ''}`);
  console.log('@walls corners');
  for (const [corner, set] of Object.entries(sets)) {
    console.log('@corner ' + corner);
    for (const [name, rows] of Object.entries(set)) console.log('@' + name + '\n' + rows.join('\n'));
  }
}
